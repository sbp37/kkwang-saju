// 올해(세운)가 원국의 어느 자리를 건드리는지까지 본다.
// 연간 십신 하나만 보던 것에 비해 훨씬 개인화된다.
function 올해정보(r, P){
  const yr = new Date().getFullYear();
  const cur = (r.seyun || []).filter(x => x.year === yr)[0];
  if (!cur) return null;
  const 이름 = ['연','월','일','시'];
  const 건드림 = [];
  P.forEach((p, i) => {
    if (p.missing) return;
    const rel = KSaju.branchRelation(cur.branch, p.branch);
    if (rel) 건드림.push({ 자리: 이름[i], 관계: rel });
  });
  const 대운관계 = r.daeunCurrent
    ? KSaju.branchRelation(cur.branch, r.daeunCurrent.branch) : null;
  return {
    연도: yr, 간지: cur.pillar, 천간십신: cur.stemGod, 지지십신: cur.branchGod,
    운성: cur.stage12, 건드림, 대운관계,
    대운: r.daeunCurrent
  };
}

// ===== 규칙 엔진 =====
// 문장마다 "언제 이 말을 하는가"를 조건으로 달아둔다.
// 사주에 맞는 규칙만 골라 점수순으로 조합하므로, 규칙을 늘리면 나올 수 있는 글도 함께 늘어난다.
function buildSlot(slot, ctx, limit) {
  const hits = [];
  for (let i = 0; i < RULES.length; i++) {
    const rule = RULES[i];
    if (rule.slot !== slot) continue;
    let ok = false;
    try { ok = rule.when(ctx); } catch (e) { ok = false; }
    if (!ok) continue;
    let text;
    try { text = typeof rule.text === 'function' ? rule.text(ctx) : rule.text; } catch (e) { continue; }
    if (!text) continue;
    hits.push({ id: rule.id, weight: rule.weight, text: text });
  }
  hits.sort((a, b) => b.weight - a.weight);
  return hits.slice(0, limit || 3);
}
function slotText(slot, ctx, limit) {
  return buildSlot(slot, ctx, limit).map(h => h.text);
}
