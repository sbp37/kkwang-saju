// 규칙들이 참조할 사주 정보를 한 곳에 모은다.
// 지금까지는 십신 그룹 5개만 봤지만, 여기서는 자리(궁위)·뿌리(통근)·격국·합충·신살까지 담는다.
const GUNG = ['연', '월', '일', '시'];
const GUNG_MEANING = {
  연: { 자리: '어릴 때와 집안', 폭: '초년과 뿌리' },
  월: { 자리: '일과 사회', 폭: '직업과 부모' },
  일: { 자리: '나 자신과 가까운 사람', 폭: '배우자와 일상' },
  시: { 자리: '나중과 결과', 폭: '말년과 자식' }
};

function buildContext() {
  const r = S.saju, y = S.yong, dm = r.dayMaster;
  const P = r.pillars;

  // 궁위: 각 자리에 어떤 십신이 앉아 있는가
  const 궁위 = {};
  GUNG.forEach((g, i) => {
    const p = P[i];
    궁위[g] = p.missing ? { missing: true } : {
      stem: p.stem, branch: p.branch,
      stemGod: p.stemGod, branchGod: p.branchGod,
      stemGroup: GROUP_OF[p.stemGod] || null,
      branchGroup: GROUP_OF[p.branchGod] || null,
      stemElem: p.stemElem, branchElem: p.branchElem,
      stage12: p.stage12, twelveSal: p.twelveSal,
      sals: p.specialSals || []
    };
  });

  // 십신 10종 카운트 (그룹 5종으로 뭉개지 않는다)
  const 십신 = {
    비견:0, 겁재:0, 식신:0, 상관:0, 편재:0,
    정재:0, 편관:0, 정관:0, 편인:0, 정인:0
  };
  P.forEach(p => {
    if (p.missing) return;
    if (p.stemGod && 십신[p.stemGod] !== undefined) 십신[p.stemGod]++;
    if (p.branchGod && 십신[p.branchGod] !== undefined) 십신[p.branchGod]++;
  });

  // 통근: 천간이 지지 어딘가에 뿌리를 두고 있는가
  const rooted = KSaju.rootedElements(r.ksajuPillars);
  const 무근천간 = [];
  P.forEach((p, i) => {
    if (p.missing || i === 2) return;
    if (!rooted[p.stemElem]) 무근천간.push({ 자리: GUNG[i], 글자: p.stem, 십신: p.stemGod, 오행: p.stemElem });
  });
  const 일간무근 = !rooted[dm.elem];

  // 투출: 지지 속에 숨어 있던 글자가 천간으로 드러났는가
  const 천간들 = P.filter(p => !p.missing).map(p => p.stem);
  const 투출 = [];
  P.forEach((p, i) => {
    if (p.missing) return;
    (KSaju.HIDDEN[p.branch] || []).forEach(h => {
      if (천간들.indexOf(h[0]) !== -1) {
        투출.push({ 자리: GUNG[i], 글자: h[0], 십신: KSaju.tenGod(dm.stem, h[0]) });
      }
    });
  });

  // 합충형파해 — 사주 안에서 글자끼리 부딪히거나 묶이는 지점
  const KEYMAP = { year:'연', month:'월', day:'일', hour:'시' };
  const 관계 = { 충:[], 합:[], 형:[], 파:[], 해:[], 원진:[], 귀문:[], 삼합:[], 육합:[], 방합:[], 반합:[] };
  (r.stemRelations || []).forEach(x => {
    const 자리 = (x.pillars || []).map(k => KEYMAP[k]).filter(Boolean);
    if (관계[x.type]) 관계[x.type].push({ 위치:'천간', 자리, 설명:x.desc });
  });
  Object.keys(r.branchRelations || {}).forEach(type => {
    if (type === '지장간' || !관계[type]) return;
    Object.keys(r.branchRelations[type] || {}).forEach(k => {
      관계[type].push({ 위치:'지지', 자리:[KEYMAP[k]].filter(Boolean), 설명:r.branchRelations[type][k] });
    });
  });
  // ssaju의 방합은 인묘진처럼 셋이 다 모였을 때만 잡는다.
  // 인묘·사오처럼 둘만 있는 반방합은 빠지므로 여기서 직접 채운다.
  for (let i = 0; i < P.length; i++) {
    for (let j = i + 1; j < P.length; j++) {
      if (P[i].missing || P[j].missing) continue;
      const bh = KSaju.banghapPair(P[i].branch, P[j].branch);
      if (!bh) continue;
      관계.방합.push({ 위치:'지지', 자리:[GUNG[i], GUNG[j]],
        설명:`${bh.pair} 반방합 → ${bh.element} 기운` });
    }
  }
  const 자리충 = new Set(관계.충.filter(x => x.위치 === '지지').flatMap(x => x.자리));

  // 신살 — 어느 자리에 붙었는지까지 본다
  const 신살 = {};
  P.forEach((p, i) => {
    if (p.missing) return;
    (p.specialSals || []).forEach(s => { (신살[s] = 신살[s] || []).push(GUNG[i]); });
    if (p.twelveSal) (신살[p.twelveSal] = 신살[p.twelveSal] || []).push(GUNG[i]);
  });

  // 공망이 어느 자리에 걸렸는가
  const 공망지지 = r.voidBranches || [];
  const 공망자리 = [];
  P.forEach((p, i) => { if (!p.missing && 공망지지.indexOf(p.branch) !== -1) 공망자리.push(GUNG[i]); });

  const 오행 = r.elems;
  const 없는오행 = ['목','화','토','금','수'].filter(e => 오행[e] === 0);
  const ranked = rankedGroups(y.g);

  return {
    일간: dm.stem, 일간오행: dm.elem, 양간: dm.yang,
    격국: y.gyeokguk, 강약: { label:y.label, strong:y.strong, weak:y.weak, score:y.score, 득령:y.득령, 득지:y.득지 },
    용신: { elem:y.elem, group:y.group, rooted:y.rooted, basis:y.basis, supplement:y.supplement, johu:y.johu },
    십신: 십신, 그룹: y.g, 그룹수: y.gc,
    dom: ranked[0], second: ranked[1], weak: ranked[ranked.length - 1],
    궁위: 궁위, 통근: rooted, 무근천간: 무근천간, 일간무근: 일간무근, 투출: 투출,
    관계: 관계, 자리충: 자리충, 신살: 신살,
    공망: 공망지지, 공망자리: 공망자리,
    오행: 오행, 없는오행: 없는오행,
    월지: P[1] ? P[1].branch : '', 일지: P[2] ? P[2].branch : '',
    일주운성: (ctx일주운성(P)), 일주신살: (P[2] && !P[2].missing) ? P[2].twelveSal : '',
    시간모름: !r.hasTime,
    대운: r.daeun, 현재대운: r.daeunCurrent, 나이: currentAge(),
    올해: 올해정보(r, P)
  };
}
