// 받침 유무에 따라 조사를 고른다. "큰 기회이야" 같은 어색한 문장을 막는다.
function hasJong(s){
  if(!s) return false;
  const c=s.charCodeAt(s.length-1);
  if(c<0xAC00||c>0xD7A3) return false;
  return (c-0xAC00)%28!==0;
}
function josa(w,pair){
  const p=pair.split('/');
  return w+(hasJong(w)?p[0]:p[1]);
}

